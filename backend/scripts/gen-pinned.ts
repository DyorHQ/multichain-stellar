// Generates ios/Packages/StellarKit/Sources/StellarCore/Network/PinnedContracts+Testnet.swift from the network registry and
// the testnet deployment: the app refuses to sign calls to any contract that isn't listed here.
//   SPONSOR_PUBLIC=G… deno run -A --config backend/supabase/functions/deno.json backend/scripts/gen-pinned.ts
import { contractAllowlist, TESTNET } from "../supabase/functions/_shared/networks.ts";
import deployment from "../supabase/functions/_shared/deployments/testnet.json" with { type: "json" };

const sponsor = Deno.env.get("SPONSOR_PUBLIC");
if (!sponsor) throw new Error("Set SPONSOR_PUBLIC (the testnet sponsor account's G-address).");
const allow = contractAllowlist(TESTNET);
const swiftArray = (xs: string[]) => `[${xs.map((x) => `"${x}"`).join(", ")}]`;
const roles = Object.entries(allow).map(([role, ids]) => `            "${role}": ${swiftArray(ids)},`).join("\n");
const out = `// Generated by backend/scripts/gen-pinned.ts from networks.ts and deployments/testnet.json — do not edit.
// Generated ${new Date().toISOString()} for deployment ${(deployment as any).deployedAt}.
import Foundation

public extension PinnedContracts {
    static let testnet = PinnedContracts(
        network: .testnet,
        sponsor: "${sponsor}",
        launchTokenWasmHash: "${(deployment as any).launchTokenWasmHash}",
        roles: [
${roles}
        ]
    )
}
`;
const path = new URL("../../ios/Packages/StellarKit/Sources/StellarCore/Network/PinnedContracts+Testnet.swift", import.meta.url).pathname;
await Deno.mkdir(path.substring(0, path.lastIndexOf("/")), { recursive: true });
await Deno.writeTextFile(path, out);
console.log("wrote", path);
